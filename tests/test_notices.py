class TestBuiltinAdapters(unittest.TestCase):
    def test_eportal(self):
        r = parse(EPORTAL, builtin_adapters())
        self.assertEqual(r.adapter, "fl-eportal-service")
        self.assertEqual(r.notice_type, "service_notice")
        self.assertEqual(r.fields["case_number"], "562026CA001234")
        self.assertEqual(len(r.fields["documents"]), 2)
        self.assertEqual(len(r.fields["served"]), 2)
        self.assertEqual(r.missing, [])

    def test_pacer_nef_captures_link_without_fetching(self):
        r = parse(NEF, builtin_adapters())
        self.assertEqual(r.adapter, "pacer-nef")
        self.assertEqual(r.fields["case_number"], "2:26-cv-01234-XYZ")
        self.assertEqual(r.fields["document_number"], "45")
        self.assertTrue(r.fields["document_link"].startswith("https://ecf.flsd.uscourts.gov/"))

    def test_jacs_hearing(self):
        r = parse(JACS, builtin_adapters())
        self.assertEqual(r.adapter, "jacs-hearing")
        self.assertEqual(r.notice_type, "hearing_notice")
        self.assertEqual(r.fields["hearing_date"], "09/15/2026")
        self.assertEqual(r.fields["hearing_time"], "10:30 AM")

    def test_efile_receipt(self):
        r = parse(RECEIPT, builtin_adapters())
        self.assertEqual(r.adapter, "efile-receipt")
        self.assertEqual(r.fields["envelope_number"], "88123456")
        self.assertEqual(r.fields["status"], "Accepted")

    def test_subject_words_cannot_satisfy_label_fields(self):
        # "SERVICE OF COURT DOCUMENT" in the subject must not populate
        # the 'court' field; labels only match at line starts.
        r = parse(EPORTAL, builtin_adapters())
        self.assertTrue(r.fields["court"].startswith("Nineteenth"))

    def test_plain_mail_no_match(self):
        self.assertIsNone(parse(PLAIN, builtin_adapters()))

    def test_required_miss_is_loud(self):
        broken = env(
            "eservice@myflcourtaccess.com",
            "SERVICE OF COURT DOCUMENT",
            "totally new template with no fields",
        )
        r = parse(broken, builtin_adapters())
        self.assertEqual(r.missing, ["case_number"])


class TestFirmAdapters(unittest.TestCase):
    def _load(self, text):
        with tempfile.TemporaryDirectory() as tmp:
            p = Path(tmp) / "adapters.toml"
            p.write_text(text)
            return load_adapters_file(p)

    def test_example_file_loads_and_overrides(self):
        adapters = load_adapters_file("examples/adapters.toml")
        self.assertEqual(adapters[0].name, "st-lucie-ja-hearing")
        e = env("ja@stlucieclerk.com", "Hearing Set",
                "Hearing Date: 10/01/2026\nTime: 9:00 AM\nJudge: Hon. X\nCase No: 562026CA000001")
        full = adapters + builtin_adapters()
        r = parse(e, full)
        self.assertEqual(r.adapter, "st-lucie-ja-hearing")

    def test_bad_notice_type_refused(self):
        with self.assertRaises(AdapterError):
            self._load('[[adapter]]\nname="x"\nnotice_type="magic"\n'
                       '[adapter.match]\nfrom="@a.com"\n[adapter.fields]\nd="(x)"')

    def test_pattern_without_group_refused(self):
        with self.assertRaises(AdapterError):
            self._load('[[adapter]]\nname="x"\nnotice_type="hearing_notice"\n'
                       '[adapter.match]\nfrom="@a.com"\n[adapter.fields]\nd="nogroup"')

    def test_required_without_pattern_refused(self):
        with self.assertRaises(AdapterError):
            self._load('[[adapter]]\nname="x"\nnotice_type="hearing_notice"\nrequired=["ghost"]\n'
                       '[adapter.match]\nfrom="@a.com"\n[adapter.fields]\nd="(x)"')

    def test_no_match_rules_refused(self):
        with self.assertRaises(AdapterError):
            self._load('[[adapter]]\nname="x"\nnotice_type="hearing_notice"\n[adapter.fields]\nd="(x)"')


class TestNoticeGate(unittest.TestCase):
    def test_gate_info_on_clean_parse(self):
        findings = NoticeParser().check(EPORTAL, {})
        self.assertEqual(len(findings), 1)
        self.assertEqual(findings[0].severity, "info")

    def test_gate_fails_loud_on_template_drift(self):
        broken = env("eservice@myflcourtaccess.com", "SERVICE OF COURT DOCUMENT", "new template")
        findings = NoticeParser().check(broken, {})
        severities = [f.severity for f in findings]
        self.assertIn("fail", severities)

    def test_gate_silent_on_ordinary_mail(self):
        self.assertEqual(NoticeParser().check(PLAIN, {}), [])



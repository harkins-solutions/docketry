def env(from_addr, subject, body):
    return Envelope(
        message_id="m", from_addr=from_addr, to=[], cc=[], date="",
        subject=subject, body_text=body, attachments=[],
        raw_sha256="e" * 64, source="t", fetched_at="now",
    )


